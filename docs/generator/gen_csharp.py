"""Generates the EF Core domain model from spec_schema.py, so C# and schema.sql cannot drift.

Outputs (under backend/src):
  SmartLMS.Domain/Entities/<Group>/<Class>.cs      one entity per table (Identity tables are hand-written)
  SmartLMS.Domain/Enums/Generated/Enums.cs         string-backed enums
  SmartLMS.Infrastructure/Persistence/Generated/GeneratedModel.cs   mapping, tenant-scoped composite FKs, indexes, checks
  SmartLMS.Infrastructure/Persistence/Generated/ApplicationDbContext.Sets.cs   DbSet properties
"""
import re
import shutil
from pathlib import Path

import gen_schema as G
import spec_schema as S

ROOT = Path(__file__).resolve().parents[2] / "backend" / "src"
SKIP = {"AspNetUsers", "AspNetRoles", "AspNetUserRoles", "AspNetUserClaims", "AspNetUserLogins", "AspNetRoleClaims", "AspNetUserTokens"}
SPECIAL_CLASS = {"AspNetUsers": "ApplicationUser", "AspNetRoles": "ApplicationRole"}
AUDITED = {"Tenants", "TenantFeatureFlags", "UserTenantMemberships", "UserDevices", "DeviceResetLogs", "Courses", "Submissions", "ExamAnswers",
           "ManualPaymentSubmissions", "VoucherBatches", "Vouchers", "InstructorPayouts", "Certificates", "ApiKeys", "WebhookEndpoints",
           "ParentStudentLinks", "Coupons", "ExamAttempts"}


def singular(n):
    if n.endswith("ies"):
        return n[:-3] + "y"
    if n.endswith("ss"):
        return n
    if n.endswith("s"):
        return n[:-1]
    return n


def cls(table):
    return SPECIAL_CLASS.get(table, singular(table))


def folder(group):
    return re.sub(r"[^A-Za-z]+", "", group.replace("&", "And"))


CLR = {"g": "Guid", "t": "string", "i": "int", "bi": "long", "b": "bool", "m": "decimal", "d": "DateTime", "o": "DateTimeOffset", "dt": "DateOnly",
       "f": "double", "j": "string", "rv": "byte[]"}


def enum_name(cl, col):
    return col if col.startswith(cl) else cl + col


def clr_type(c, cl):
    t = c["type"]
    if c["enum"]:
        return enum_name(cl, c["name"])
    if t.startswith("s:"):
        return "string"
    return CLR[t]


def initializer(c, cl):
    t = c["type"]
    d = c["default"]
    nullable = c["nullable"]
    if c["enum"]:
        return f" = {enum_name(cl, c['name'])}.{d.strip(chr(39))};" if d and not nullable else ""
    if t.startswith("s:") or t in ("t", "j"):
        if nullable:
            return ""
        if d and d.startswith("'"):
            return f' = "{d.strip(chr(39))}";'
        return ' = "{}";' if t == "j" else " = string.Empty;"
    if t == "rv":
        return " = [];"
    if d is None or nullable:
        return ""
    if t == "b":
        return " = true;" if d == "1" else " = false;"
    if t == "m":
        return f" = {d}m;"
    if t == "f":
        return f" = {d};"
    if t == "i":
        return f" = {d};"
    return ""


def gen_entities():
    ent_root = ROOT / "SmartLMS.Domain" / "Entities"
    if ent_root.exists():
        shutil.rmtree(ent_root)
    enum_lines = ["// <auto-generated> by docs/generator/gen_csharp.py. Do not edit. </auto-generated>", "#nullable enable", "namespace SmartLMS.Domain.Enums;", ""]
    count = 0
    for t in S.TABLES:
        n = t["name"]
        if n in SKIP:
            continue
        cl = cls(n)
        fl = t["flags"]
        ifaces = ["BaseEntity"]
        if "T" in fl:
            ifaces.append("ITenantEntity")
        if "N" in fl:
            ifaces.append("INullableTenantEntity")
        if "A" in fl:
            ifaces.append("IAuditableEntity")
        if "S" in fl:
            ifaces.append("ISoftDeletable")
        lines = ["// <auto-generated> by docs/generator/gen_csharp.py. Do not edit. </auto-generated>", "#nullable enable", "using SmartLMS.Domain.Common;", "using SmartLMS.Domain.Enums;", "",
                 "namespace SmartLMS.Domain.Entities;", ""]
        if t["note"]:
            lines.append("/// <summary>" + t["note"].replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") + "</summary>")
        if n in AUDITED:
            lines.append("[AuditedEntity]")
        lines.append(f"public class {cl} : {', '.join(ifaces)}")
        lines.append("{")
        for c in G.full_cols(t):
            if c["name"] == "Id":
                continue
            ty = clr_type(c, cl)
            if c["nullable"] and ty != "string":
                ty += "?"
            elif c["nullable"]:
                ty += "?"
            if c["enum"]:
                members = c["enum"]
                enum_lines.append(f"public enum {enum_name(cl, c['name'])}")
                enum_lines.append("{")
                enum_lines += [f"    {m}," for m in members]
                enum_lines.append("}")
                enum_lines.append("")
            lines.append(f"    public {ty} {c['name']} {{ get; set; }}{initializer(c, cl)}")
        lines.append("}")
        d = ent_root / folder(t["group"])
        d.mkdir(parents=True, exist_ok=True)
        (d / f"{cl}.cs").write_text("\n".join(lines) + "\n")
        count += 1
    ed = ROOT / "SmartLMS.Domain" / "Enums" / "Generated"
    ed.mkdir(parents=True, exist_ok=True)
    (ed / "Enums.cs").write_text("\n".join(enum_lines))
    return count


def q(s):
    return '"' + s + '"'


def gen_model():
    out = ["// <auto-generated> by docs/generator/gen_csharp.py from docs/generator/spec_schema.py. Do not edit. </auto-generated>",
           "using Microsoft.EntityFrameworkCore;", "using SmartLMS.Domain.Entities;", "using SmartLMS.Infrastructure.Identity;", "using SmartLMS.Domain.Enums;", "",
           "namespace SmartLMS.Infrastructure.Persistence.Generated;", "",
           "/// <summary>Maps every table. All foreign keys are NO ACTION. Foreign keys between tenant-owned tables are composite (TenantId, X) so the database rejects cross-tenant references.</summary>",
           "public static class GeneratedModel", "{"]
    # alternate keys
    alt = {}
    for t in S.TABLES:
        for c in G.full_cols(t):
            if c["fk"]:
                kind, cc, pt, pc = G.fk_plan(t, c)
                if kind == "composite":
                    alt.setdefault(pt, set()).add(tuple(pc))
    names = []
    for t in S.TABLES:
        n = t["name"]
        if n in SKIP:
            continue
        cl = cls(n)
        cols = G.full_cols(t)
        soft = "S" in t["flags"]
        body = []
        a = body.append
        a("        b.Property(e => e.Id).ValueGeneratedNever();")
        for c in cols:
            nm = c["name"]
            if nm == "Id":
                continue
            ty = c["type"]
            if c["enum"]:
                a(f"        b.Property(e => e.{nm}).HasConversion<string>().HasMaxLength(40);")
            elif ty.startswith("s:"):
                a(f"        b.Property(e => e.{nm}).HasMaxLength({ty[2:]});")
            elif ty == "m":
                a(f"        b.Property(e => e.{nm}).HasPrecision(18, 2);")
            elif ty == "rv":
                a(f"        if (sqlServer) b.Property(e => e.{nm}).IsRowVersion(); else b.Ignore(e => e.{nm});")
        for pc in sorted(alt.get(n, [])):
            if pc != ("Id",):
                a(f"        b.HasAlternateKey({', '.join(q(x) for x in pc)});")
        # indexes
        uniq = [(list(u)) for u in t["uniq"]] + [[c["name"]] for c in cols if c["unique"]]
        for u in uniq:
            where = []
            if len(u) == 1 and next(cc for cc in cols if cc["name"] == u[0])["nullable"]:
                where.append(f"[{u[0]}] IS NOT NULL")
            if soft:
                where.append("[IsDeleted] = 0")
            f = f'.HasFilter("{" AND ".join(where)}")' if where else ""
            a(f"        b.HasIndex({', '.join(q(x) for x in u)}).IsUnique().HasDatabaseName({q('UX_' + n + '_' + '_'.join(u))}){f};")
        for u in t["idx"]:
            a(f"        b.HasIndex({', '.join(q(x) for x in u)}).HasDatabaseName({q('IX_' + n + '_' + '_'.join(u))});")
        # relationships
        for c in cols:
            if not c["fk"]:
                continue
            kind, cc, pt, pc = G.fk_plan(t, c)
            parent = cls(pt)
            if kind == "plain":
                a(f"        b.HasOne<{parent}>().WithMany().HasForeignKey({', '.join(q(x) for x in cc)}).OnDelete(DeleteBehavior.NoAction);")
            else:
                req = "" if not c["nullable"] else ".IsRequired(false)"
                a(f"        b.HasOne<{parent}>().WithMany().HasForeignKey({', '.join(q(x) for x in cc)}).HasPrincipalKey({', '.join(q(x) for x in pc)}){req}.OnDelete(DeleteBehavior.NoAction);")
        # checks
        ck = []
        for c in cols:
            if c["enum"]:
                vals = ",".join("'" + v + "'" for v in c["enum"])
                ck.append(f'            t.HasCheckConstraint({q("CK_" + n + "_" + c["name"])}, {q("[" + c["name"] + "] IN (" + vals + ")")});')
        for i, rule in enumerate(G.CHECKS.get(n, [])):
            ck.append(f'            t.HasCheckConstraint({q(f"CK_{n}_Rule{i + 1}")}, {q(rule)});')
        for c in cols:
            if c["type"] == "j":
                ck.append(f'            if (sqlServer) t.HasCheckConstraint({q("CK_" + n + "_" + c["name"] + "_Json")}, {q("ISJSON([" + c["name"] + "]) = 1")});')
        out.append(f"    private static void Map{cl}(ModelBuilder mb, bool sqlServer)")
        out.append("    {")
        out.append(f"        mb.Entity<{cl}>(b =>")
        out.append("        {")
        out.append(f"        b.ToTable({q(n)}, t =>")
        out.append("        {")
        out.extend(ck)
        out.append("        });")
        out.extend(body)
        out.append("        });")
        out.append("    }")
        out.append("")
        names.append(cl)
    out.append("    public static void Apply(ModelBuilder mb, bool sqlServer)")
    out.append("    {")
    for cl in names:
        out.append(f"        Map{cl}(mb, sqlServer);")
    out.append("    }")
    out.append("}")
    d = ROOT / "SmartLMS.Infrastructure" / "Persistence" / "Generated"
    d.mkdir(parents=True, exist_ok=True)
    (d / "GeneratedModel.cs").write_text("\n".join(out) + "\n")
    sets = ["// <auto-generated> by docs/generator/gen_csharp.py. Do not edit. </auto-generated>", "using Microsoft.EntityFrameworkCore;", "using SmartLMS.Domain.Entities;", "using SmartLMS.Infrastructure.Identity;", "",
            "namespace SmartLMS.Infrastructure.Persistence;", "", "public partial class ApplicationDbContext", "{"]
    for t in S.TABLES:
        if t["name"] in SKIP:
            continue
        sets.append(f"    public DbSet<{cls(t['name'])}> {t['name']} => Set<{cls(t['name'])}>();")
    sets.append("}")
    (d / "ApplicationDbContext.Sets.cs").write_text("\n".join(sets) + "\n")
    return len(names)


if __name__ == "__main__":
    n = gen_entities()
    m = gen_model()
    print("entities", n, "mapped", m)
